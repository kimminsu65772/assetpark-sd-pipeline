def 보기갱신(a, 이름, 번호, 인자) -> dict:
    """켜져 있는 서버에 모델을 다시 묻는다(서버가 새 작업본해시의 GLB를 만들기 시작). 서버가 없으면 여기서 만든다."""
    포트 = 서버.같은폴더서버(a.폴더)
    if 포트 is not None:
        c = http.client.HTTPConnection(서버.주소, 포트, timeout=10)
        c.request("GET", "/api/" + urllib.parse.quote("모델") + "?" + urllib.parse.urlencode({"이름": 이름}),
                  headers={"Host": f"{서버.주소}:{포트}"})
        r = c.getresponse()
        v = json.loads(r.read() or b"{}")
        if r.status != 200:
            틀림(f"서버가 모델을 만들지 못했습니다: {v.get('오류')}")
        return {"결과": "서버에 알림", "포트": 포트, "상태": v.get("상태"), "작업본해시": v.get("작업본해시"),
                "글": "페이지가 몇 초 안에 새 모델로 바뀝니다(만드는 중이면 조금 더)."}
    f = a.작업본파일(이름)
    if not f:
        틀림("상태.json의 작업본이 없습니다.")
    r = 서버.보기만들기.만들기(f, a.보기폴더(이름, 만들기=True))
    if r.get("상태") == "실패":
        틀림(f"GLB를 만들지 못했습니다: {r.get('오류')}")
    return {"결과": "만듦(서버 꺼짐)", "상태": r.get("상태"), "작업본해시": 서버.파일해시(f)}


def 부위(a, 이름, 번호, 인자) -> dict:
    """부위 목록 쓰기(W05의 이어받기·목록다듬기·쓰기를 그대로). 파일 꼴: {부위: [{이름, 파츠, 면, 자동이름?, 중심?}], 파츠: [{이름, 크기}]}"""
    v = 읽기(인자.값[0] if 인자.값 else 틀림("부위 파일 경로가 없습니다."))
    목록 = v.get("부위")
    if not isinstance(목록, list) or not 목록:
        틀림("'부위'가 비었거나 목록이 아닙니다.")
    for r in 목록:
        if (not isinstance(r, dict) or not isinstance(r.get("이름"), str) or not r["이름"].strip()
                or not isinstance(r.get("파츠"), str) or not isinstance(r.get("면"), list)
                or not all(isinstance(i, int) and not isinstance(i, bool) and i >= 0 for i in r["면"])):
            틀림(f"부위 한 줄이 꼴에 맞지 않습니다(이름·파츠 글, 면 정수 목록): {str(r)[:120]}")
    if not isinstance(v.get("파츠", []), list):
        틀림("'파츠'는 목록이어야 합니다.")
    p = a.부위파일(이름)
    if p.exists() and not a._안전한파일(p, a.캐릭터폴더(이름)):
        틀림("부위.json이 일반 파일이 아닙니다(링크).")
    옛값 = None
    if p.is_file():
        try:
            옛값 = json.loads(p.read_text(encoding="utf-8"))
        except ValueError:
            옛값 = None
    값 = 부위만들기.목록다듬기(v, a._지금작업본해시(이름), 옛값)
    값["만든곳"] = "10_제작페이지/에이전트.py 부위"
    부위만들기.쓰기(p, 값)
    서버.기록(f"부위 목록: {len(값['부위'])}개, 이어받은 이름 {값['이어받은이름']}", a, 이름)
    return {"결과": "씀", "파일": p.relative_to(a.폴더).as_posix(), "부위수": len(값["부위"]), "이어받은이름": 값["이어받은이름"]}


