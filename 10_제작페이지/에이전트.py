def 틀림(글: str):
    raise 요청오류(400, 글)


def 읽기(경로: str) -> dict:
    p = Path(경로)
    try:
        v = json.loads(p.read_text(encoding="utf-8"))
    except FileNotFoundError:
        틀림(f"파일이 없습니다: {경로}")
    except ValueError as e:
        틀림(f"JSON을 읽지 못했습니다({경로}): {e}")
    if not isinstance(v, dict):
        틀림(f"맨 바깥이 객체가 아닙니다: {경로}")
    return v


def 그림확인(a: 서버.앱, 목록, 어디: str, 꼭: bool) -> list[str]:
    if 목록 is None:
        목록 = []
    if not isinstance(목록, list) or not all(isinstance(x, str) for x in 목록):
        틀림(f"{어디}: 그림은 경로(글) 목록이어야 합니다.")
    if 꼭 and not 목록:
        틀림(f"{어디}: 근거그림(전후)이 있어야 합니다.")
    없음 = [x for x in 목록 if a.저장소파일(x) is None]
    if 없음:
        틀림(f"{어디}: 저장소 안에 없는 그림(저장소 루트 기준 경로로): {', '.join(없음)}")
    return 목록


def 표시항목검사(a: 서버.앱, x, 어디: str, 근거꼭: bool) -> None:
    """2-1 "표시 항목"의 모양. 후보·고친 것에 쓴다."""
    if not isinstance(x, dict):
        틀림(f"{어디}: 한 줄이 객체가 아닙니다.")
    n = x.get("번호")
    if not isinstance(n, str) or not n or len(n) > 8:
        틀림(f"{어디}: '번호'가 비었거나 너무 깁니다.")
    if x.get("누가") not in 만든이들:
        틀림(f"{어디} {n}: '누가'는 {' / '.join(만든이들)} 가운데 하나.")
    if not isinstance(x.get("종류"), str) or not x["종류"]:
        틀림(f"{어디} {n}: '종류'가 없습니다.")
    if x.get("판단") not in (None, ""):
        틀림(f"{어디} {n}: '판단'은 비워 둡니다(사용자가 페이지에서 정함).")
    자리 = x.get("자리")
    if not isinstance(자리, dict) or not isinstance(자리.get("파츠", []), list) or not isinstance(자리.get("면", {}), dict):
        틀림(f"{어디} {n}: '자리'가 2-1 꼴이 아닙니다({{파츠: [...], 면: {{파츠: [면 번호]}}}}).")
    for p, 면 in 자리.get("면", {}).items():
        if not isinstance(면, list) or not all(isinstance(i, int) and not isinstance(i, bool) and i >= 0 for i in 면):
            틀림(f"{어디} {n}: 면 번호는 0 이상의 정수 목록({p}).")
    if not isinstance(x.get("반대쪽도", False), bool):
        틀림(f"{어디} {n}: '반대쪽도'는 참/거짓.")
    if x.get("종류") == "기타" and not str(x.get("메모", "")).strip():
        틀림(f"{어디} {n}: 종류가 '기타'면 메모가 있어야 합니다.")
    그림확인(a, x.get("근거그림"), f"{어디} {n}", 근거꼭)


