def 받기(a, 이름, 번호, 인자) -> dict:
    묶음 = a.묶음들(이름, 번호)
    합쳐진 = {str(f) for _, v in 묶음 for f in (v.get("합친묶음") or [])}
    남은 = [(q, v) for q, v in 묶음 if q.name not in 합쳐진]
    하던 = [(q, v) for q, v in 남은 if v.get("묶음상태") == "처리 중"]
    다시 = bool(하던)
    고른 = 하던[:1] or [(q, v) for q, v in 남은 if v.get("묶음상태") == "보냄"][:1]
    if not 고른:
        return {"결과": "없음", "글": f"{번호}단계에 보낸(\"보냄\") 묶음이 없습니다."}
    q, v = 고른[0]
    if not 다시:
        a.묶음상태쓰기(이름, 번호, q.name, "처리 중", {"받은시각": 서버.지금()})
        a.단계상태쓰기(이름, 번호, {"상태": "진행 중"})
    지금h = a._지금작업본해시(이름)
    작업본 = a.작업본파일(이름)
    표시 = []
    for x in v.get("표시") or []:
        if not isinstance(x, dict):
            continue
        자리 = x.get("자리") or {}
        h = x.get("작업본해시") or v.get("작업본해시") or ""
        표시.append({"번호": x.get("번호"), "종류": x.get("종류"), "메모": x.get("메모", ""), "반대쪽도": bool(x.get("반대쪽도")),
                   "파츠": 자리.get("파츠") or [], "부위": 자리.get("부위") or [],
                   "면수": {p: len(m) for p, m in (자리.get("면") or {}).items() if isinstance(m, list)},
                   "UV": 자리.get("UV"), "옛버전": bool(h and 지금h and h != 지금h)})
    return {"결과": "받음", "다시받음": 다시, "묶음": q.name, "경로": q.relative_to(a.폴더).as_posix(),
            "합친묶음": v.get("합친묶음") or [], "작업본": 작업본.relative_to(a.폴더).as_posix() if 작업본 else "",
            "작업본해시": 지금h, "결정": v.get("결정", "없음"), "표시": 표시, "후보판단": v.get("후보판단") or [],
            "멈춤답": v.get("멈춤답"),   # W11 3단계: 멈춤 1이면 사용자가 정한 대칭(기준쪽은 바꾸지 않음)
            "해야할것": "모든 번호(표시·후보판단)마다 고침/안 고침을 처리 파일에 적는다. 작업본을 바꾸기 전에 '사본'을 먼저."}


def 사본(a, 이름, 번호, 인자) -> dict:
    return a.사본만들기(이름, 번호, 인자.까닭 or "에이전트가 고치기 직전")


def 후보(a, 이름, 번호, 인자) -> dict:
    return 후보쓰기(a, 이름, 번호, 읽기(인자.값[0] if 인자.값 else 틀림("후보 파일 경로가 없습니다.")))


def 후보쓰기(a, 이름, 번호, v: dict, 덧: dict | None = None) -> dict:
    """후보_<시각>.json을 쓴다. `덧`은 단계 화면이 더하는 항목(W11 3단계: 멈춤·계획·결과)."""
    if v.get("만든이", "에이전트") not in 만든이들:
        틀림(f"'만든이'는 {' / '.join(만든이들)} 가운데 하나.")
    후보들, 고친것 = v.get("후보", []), v.get("고친것", [])
    if not isinstance(후보들, list) or not isinstance(고친것, list):
        틀림("'후보'·'고친것'은 목록이어야 합니다.")
    if not 후보들 and not 고친것 and not 덧:
        틀림("후보도 고친 것도 없습니다.")
    본 = set()
    for x in 후보들:
        표시항목검사(a, x, "후보", 근거꼭=False)
    for x in 고친것:
        표시항목검사(a, x, "고친것", 근거꼭=True)
    for x in 후보들 + 고친것:
        if x["번호"] in 본:
            틀림(f"번호가 겹칩니다: {x['번호']}")
        본.add(x["번호"])
    d = a.단계폴더(이름, 번호, 만들기=True)
    시각 = 서버.지금(파일용=True)
    q, k = d / f"후보_{시각}.json", 2
    while q.exists():
        q, k = d / f"후보_{시각}_{k}.json", k + 1
    with 서버.파일잠금(q):
        서버.json_쓰기(q, {"꼴버전": 서버.꼴버전, "만든시각": 서버.지금(), "작업본해시": a._지금작업본해시(이름), "단계": 번호,
                         "만든이": v.get("만든이", "에이전트"), "후보": 후보들, "고친것": 고친것, **(덧 or {})})
    a.단계상태쓰기(이름, 번호, {"상태": "결정 대기"})
    서버.기록(f"후보: {번호}단계 {q.name} (후보 {len(후보들)}, 고친 것 {len(고친것)})", a, 이름)
    return {"결과": "씀", "파일": q.relative_to(a.폴더).as_posix(), "후보수": len(후보들), "고친것수": len(고친것), "단계상태": "결정 대기"}


def 처리(a, 이름, 번호, 인자) -> dict:
    if len(인자.값) != 2:
        틀림("처리 <묶음 파일 이름> <처리 결과 파일.json> 꼴로 주세요.")
    묶음, 결과파일 = 인자.값
    묶음 = Path(묶음).name
    if not 묶음이름.fullmatch(묶음):
        틀림(f"묶음 이름이 잘못됨: {묶음}")
    짝 = dict((q.name, v) for q, v in a.묶음들(이름, 번호))
    if 묶음 not in 짝:
        틀림(f"{번호}단계에 그 묶음이 없습니다: {묶음}")
    b = 짝[묶음]
    if b.get("묶음상태") != "처리 중":
        틀림(f"묶음 상태가 '{b.get('묶음상태')}'입니다. '받기'로 받은(처리 중) 묶음만 처리합니다.")
    v = 읽기(결과파일)
    결과 = v.get("결과")
    if not isinstance(결과, list):
        틀림("'결과'가 목록이 아닙니다.")
    필요 = [x.get("번호") for x in (b.get("표시") or []) if isinstance(x, dict)] + \
          [x.get("번호") for x in (b.get("후보판단") or []) if isinstance(x, dict)]
    본: dict[str, dict] = {}
    for r in 결과:
        if not isinstance(r, dict) or not isinstance(r.get("번호"), str):
            틀림("결과 한 줄에 '번호'(글)가 없습니다.")
        n = r["번호"]
        if n in 본:
            틀림(f"결과에 같은 번호가 두 번 있습니다: {n}")
        if n not in 필요:
            틀림(f"묶음에 없는 번호입니다: {n}")
        if r.get("처리") not in 처리값:
            틀림(f"{n}: '처리'는 '고침' 또는 '안 고침'.")
        if r["처리"] == "안 고침" and not str(r.get("이유", "")).strip():
            틀림(f"{n}: 안 고침이면 이유가 있어야 합니다(예: 자리를 못 찾음, 입력 그림에 있음, 동작 문제).")
        if r["처리"] == "고침":
            그림확인(a, r.get("근거그림"), f"{n}의 근거그림", 꼭=True)
        본[n] = r
    빠짐 = [n for n in 필요 if n not in 본]
    if 번호 == 서버.동작단계.애니:  # W14: 10단계는 줄마다 '쪽'(동작 / 리깅)
        서버.동작단계.처리쪽검사(list(본.values()))
    if 빠짐:
        틀림(f"결과가 빠진 항목이 있어 처리됨으로 바꾸지 않습니다: {', '.join(map(str, 빠짐))}")
    고침수 = sum(1 for r in 본.values() if r["처리"] == "고침")
    사본경로 = v.get("되돌리기사본") or ""
    if 고침수:
        if a.저장소파일(사본경로) is None or "/되돌리기/" not in str(사본경로).replace("\\", "/"):
            틀림("고친 항목이 있으면 '되돌리기사본'(사본 명령이 준 경로)이 있어야 합니다.")
    열어본 = 그림확인(a, v.get("열어본그림"), "열어본그림", 꼭=False)
    만들기만 = 그림확인(a, v.get("만들기만한그림"), "만들기만한그림", 꼭=False)
    d = a.단계폴더(이름, 번호, 만들기=False)
    시각 = 서버.지금(파일용=True)
    q, k = d / f"처리_{시각}.json", 2
    while q.exists():
        q, k = d / f"처리_{시각}_{k}.json", k + 1
    with 서버.파일잠금(q):
        서버.json_쓰기(q, {"꼴버전": 서버.꼴버전, "만든시각": 서버.지금(), "작업본해시": a._지금작업본해시(이름), "단계": 번호,
                         "묶음": 묶음, "결과": [본[n] for n in 필요], "되돌리기사본": 사본경로,
                         "열어본그림": 열어본, "만들기만한그림": 만들기만})
    바꾼 = a.묶음상태쓰기(이름, 번호, 묶음, "처리됨")
    a.단계상태쓰기(이름, 번호, {"상태": "결정 대기"})
    return {"결과": "씀", "파일": q.relative_to(a.폴더).as_posix(), "처리됨": 바꾼, "고침": 고침수,
            "안고침": len(본) - 고침수, "단계상태": "결정 대기",
            "다음": "알림을 쓰고(열어 본 그림 / 만들기만 한 그림 구분), 작업본을 바꿨으면 보기갱신."}


def 실패(a, 이름, 번호, 인자) -> dict:
    if len(인자.값) != 2 or not 인자.값[1].strip():
        틀림('실패 <묶음 파일 이름> "<이유>" 꼴로 주세요.')
    묶음, 이유 = Path(인자.값[0]).name, 인자.값[1].strip()
    짝 = dict((q.name, v) for q, v in a.묶음들(이름, 번호))
    if 묶음 not in 짝:
        틀림(f"{번호}단계에 그 묶음이 없습니다: {묶음}")
    if 짝[묶음].get("묶음상태") not in ("보냄", "처리 중"):
        틀림(f"묶음 상태가 '{짝[묶음].get('묶음상태')}'입니다. 보냄·처리 중인 묶음만 실패로 바꿉니다.")
    바꾼 = a.묶음상태쓰기(이름, 번호, 묶음, "실패", {"실패이유": 이유})
    a.단계상태쓰기(이름, 번호, {"상태": "막힘"})
    a.알림쓰기(이름, 번호, f"끝내지 못함: {이유}\n페이지에서 이 묶음을 다시 보낼 수 있습니다.", "막힘")
    return {"결과": "씀", "실패": 바꾼, "단계상태": "막힘"}


